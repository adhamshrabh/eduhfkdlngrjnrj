/**
 * game/scenes/ActivityLayout.ts
 *
 * أين تقع صورةٌ لم تُسحَب بعد — تعريفٌ واحد لكل نشاط يرسم صوراً.
 *
 * ⚠️ لماذا ملفّ لثلاثة أرقام:
 *
 * كانت هذه الأرقام تعيش داخل `PickCorrectRunner`، ويُعيد `SceneCanvas` في
 * الاستوديو كتابتها لأن الاستوديو لا يعتمد على `@game`. ونسخةٌ ثالثة —
 * لـ«الترتيب» (v1.0.23) — كانت ستجعل الوعد ثلاثيّاً: ثلاثة مواضع يجب أن
 * تتفق، واثنان منها في المحرّك نفسه.
 *
 * فالمحرّك يعرّفها هنا مرّةً واحدة، ويبقى تكرار الاستوديو وحده — وهو الذي
 * يحرسه `ChoiceLayout.test.ts` بقراءة هذا الملف.
 *
 * ومعنى الاتفاق ليس تجميلياً: الاستوديو يرسم ما ستضعه المعلّمة، فمسرحٌ يكذب
 * عن النتيجة أسوأ من غياب المسرح — لأنها تثق بما وضعته.
 */

/** فضاء التصميم الذي تُقاس فيه كل هذه المواضع. */
export const DESIGN_WIDTH = 1920;
export const DESIGN_HEIGHT = 1080;

/**
 * صندوق الحوار: كم يرتفع أعلاه عن أسفل فضاء التصميم، وكم ارتفاعه.
 *
 * ⚠️ لماذا هنا لا في `DialoguePlayer` وحده: الصندوق **يحتلّ آخر ٢٢٠ بكسل
 * من المسرح**، وكل نشاطٍ يرسم رفّاً أو صفّاً أسفل الشاشة يزاحمه عليها.
 * وقد كان الرقم مكتوباً في مكانٍ واحد لا يقرؤه أحد، فوضع `JigsawRunner`
 * قطعه عند ١٠٠٠ — داخل الصندوق، وحافّتها السفلى خارج المسرح.
 *
 * فالمعرفة تُنشَر هنا حيث تقرؤها الطبقتان، لا تبقى حبيسة من يرسم الصندوق.
 */
export const DIALOGUE_BOX_OFFSET = 220;
export const DIALOGUE_BOX_HEIGHT = 180;

/** أعلى صندوق الحوار — سقفُ أي شيءٍ يُرسم أسفل المسرح. */
export const DIALOGUE_TOP = DESIGN_HEIGHT - DIALOGUE_BOX_OFFSET;

/** هامشٌ بين أدنى ما يُرسم وأعلى الصندوق — كي لا يتلامسا. */
export const FLOOR_MARGIN = 16;

/** أدنى حافّةٍ يجوز أن يبلغها شيءٌ مرسوم على المسرح. */
export const STAGE_FLOOR = DIALOGUE_TOP - FLOOR_MARGIN;

/**
 * أين تهبط الصور غير الموضوعة — منشورةً لا مكدّسة.
 *
 * الدرس نفسه الذي يسجّله `SpriteRegistry.showSceneElement`: مواضع افتراضية
 * متطابقة تجعل عدّة صور تبدو صورةً واحدة مفقودة.
 */
export const SPREAD_Y = 760;
export const SPREAD_GAP = 320;

/**
 * ارتفاع الصورة على المسرح. ثابتٌ لا مؤلَّف: ما يقارنه الطفل يجب ألّا يختلف
 * في الوزن البصري، وإلّا وُجد الجواب بالنظر بدل الإصغاء.
 */
export const CHOICE_HEIGHT = 220;

/** أوّل x في صفٍّ من `total` صورة، متوسّطاً على عرض التصميم. */
export function spreadStartX(total: number): number {
  return DESIGN_WIDTH / 2 - ((total - 1) * SPREAD_GAP) / 2;
}
