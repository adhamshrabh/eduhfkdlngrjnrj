/** فضاء التصميم الذي تُقاس فيه كل هذه المواضع. */
export const DESIGN_WIDTH = 1920;

/**
 * أين تهبط الصور غير الموضوعة — منشورةً لا مكدّسة.
 *
 * الدرس نفسه الذي يسجّله `SpriteRegistry.showSceneElement`: مواضع افتراضية
 * متطابقة تجعل عدّة صور تبدو صورةً واحدة مفقودة.
 */
export const SPREAD_Y = 760;
export const SPREAD_GAP = 320;

/**
 * ارتفاع الصورة على المسرح. ثابتٌ لا مؤلَّف: ما يقارنه الطفل يجب ألّا يختلف
 * في الوزن البصري، وإلّا وُجد الجواب بالنظر بدل الإصغاء.
 */
export const CHOICE_HEIGHT = 220;

/** أوّل x في صفٍّ من `total` صورة، متوسّطاً على عرض التصميم. */
export function spreadStartX(total: number): number {
  return DESIGN_WIDTH / 2 - ((total - 1) * SPREAD_GAP) / 2;
}
